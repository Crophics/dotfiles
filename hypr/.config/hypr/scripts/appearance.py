#!/usr/bin/env python3
"""Cursor, icon and font settings for the Settings app.

  appearance.py get                      current values as JSON
  appearance.py list cursors|icons|fonts|mono
  appearance.py cursor <theme> <size>    GTK, Hyprland, XWayland and the next login
  appearance.py icons <theme>
  appearance.py font <family> <size>     interface font
  appearance.py mono <family> <size>     monospace font

Changes go to gsettings (live for GTK 3/4 apps), the GTK settings.ini files, and for the
cursor also hypr/appearance.lua (read by hyprland.lua at login) and ~/.icons/default.
"""
import glob, json, os, re, subprocess, sys

HOME = os.path.expanduser("~")
SCHEMA = "org.gnome.desktop.interface"
ICON_DIRS = ["/usr/share/icons", f"{HOME}/.local/share/icons", f"{HOME}/.icons"]
INIS = [f"{HOME}/.config/gtk-3.0/settings.ini", f"{HOME}/.config/gtk-4.0/settings.ini"]
APPEARANCE_LUA = f"{HOME}/.config/hypr/appearance.lua"
HIDDEN = {"default", "hicolor", "locolor", "HighContrast", "AdwaitaLegacy"}


def run(*a):
    return subprocess.run(list(a), capture_output=True, text=True).stdout.strip()


def gget(key):
    return run("gsettings", "get", SCHEMA, key).strip("'")


def gset(key, value):
    subprocess.run(["gsettings", "set", SCHEMA, key, str(value)], capture_output=True)


def ini_set(key, value):
    for path in INIS:
        try:
            text = open(path).read()
        except OSError:
            continue
        if re.search(rf"^{re.escape(key)}=", text, re.M):
            text = re.sub(rf"^{re.escape(key)}=.*$", f"{key}={value}", text, flags=re.M)
        elif "[Settings]" in text:
            text = text.replace("[Settings]", f"[Settings]\n{key}={value}", 1)
        else:
            continue
        open(path, "w").write(text)


def themes(kind):
    out = set()
    for d in ICON_DIRS:
        for p in glob.glob(f"{d}/*/"):
            name = os.path.basename(p.rstrip("/"))
            if name in HIDDEN:
                continue
            has_cursors = os.path.isdir(p + "cursors") or os.path.isdir(p + "hyprcursors")
            has_icons = os.path.exists(p + "index.theme") and any(
                os.path.isdir(p + s) for s in ("scalable", "16x16", "22x22", "24x24", "32x32", "48x48", "symbolic", "places"))
            if (kind == "cursors" and has_cursors) or (kind == "icons" and has_icons):
                out.add(name)
    return sorted(out, key=str.lower)


def fonts(mono=False):
    args = ["fc-list", ":spacing=100", "family"] if mono else ["fc-list", ":", "family"]
    names = set()
    for line in run(*args).splitlines():
        first = line.split(",")[0].strip()
        if first and not first.startswith(".") and not first.endswith(".pcf"):
            names.add(first)
    return sorted(names, key=str.lower)


def split_font(s):
    m = re.match(r"^(.*?)\s+(\d+(?:\.\d+)?)$", s)
    return (m.group(1), float(m.group(2))) if m else (s, 11.0)


def cursor(theme, size):
    gset("cursor-theme", f"'{theme}'")
    gset("cursor-size", size)
    ini_set("gtk-cursor-theme-name", theme)
    ini_set("gtk-cursor-theme-size", size)
    with open(APPEARANCE_LUA, "w") as f:
        f.write("-- Generated by scripts/appearance.py from Settings > Appearance. Do not edit.\n")
        f.write(f'return {{ cursor_theme = "{theme}", cursor_size = {int(size)} }}\n')
    os.makedirs(f"{HOME}/.icons/default", exist_ok=True)
    with open(f"{HOME}/.icons/default/index.theme", "w") as f:
        f.write(f"[Icon Theme]\nName=Default\nComment=Default Cursor Theme\nInherits={theme}\n")
    subprocess.run(["hyprctl", "setcursor", theme, str(size)], capture_output=True)
    subprocess.run(["hyprctl", "eval", f'hl.env("XCURSOR_THEME", "{theme}"); hl.env("XCURSOR_SIZE", "{int(size)}")'],
                   capture_output=True)


def main():
    a = sys.argv[1:]
    cmd = a[0] if a else ""
    if cmd == "get":
        fam, size = split_font(gget("font-name"))
        mfam, msize = split_font(gget("monospace-font-name"))
        print(json.dumps({"cursor": gget("cursor-theme"), "cursorSize": int(gget("cursor-size") or 24),
                          "icons": gget("icon-theme"), "font": fam, "fontSize": size,
                          "mono": mfam, "monoSize": msize}))
    elif cmd == "list" and len(a) == 2:
        print(json.dumps(fonts(a[1] == "mono") if a[1] in ("fonts", "mono") else themes(a[1])))
    elif cmd == "cursor" and len(a) == 3:
        cursor(a[1], int(a[2]))
    elif cmd == "icons" and len(a) == 2:
        gset("icon-theme", f"'{a[1]}'")
        ini_set("gtk-icon-theme-name", a[1])
    elif cmd == "font" and len(a) == 3:
        gset("font-name", f"'{a[1]} {a[2]}'")
        ini_set("gtk-font-name", f"{a[1]} {a[2]}")
    elif cmd == "mono" and len(a) == 3:
        gset("monospace-font-name", f"'{a[1]} {a[2]}'")
    else:
        sys.exit(__doc__)


main()
