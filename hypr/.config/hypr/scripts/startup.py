#!/usr/bin/env python3
"""Login apps from Settings > Apps. Reads quickshell/state/startup.json, a list of
{"name", "command", "enabled"}, and writes hypr/startup.lua (required by hyprland.lua)."""
import json, os

HOME = os.path.expanduser("~")
STATE = f"{HOME}/.config/quickshell/state/startup.json"
OUT = f"{HOME}/.config/hypr/startup.lua"

try:
    items = json.load(open(STATE))
except (OSError, ValueError):
    items = []

def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

lines = ["-- Generated by scripts/startup.py from Settings > Apps. Do not edit.", 'hl.on("hyprland.start", function()']
for i in items:
    if i.get("enabled", True) and i.get("command"):
        lines.append(f"    hl.exec_cmd({q(i['command'])})")
lines.append("end)")
with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
