#!/usr/bin/env python3
"""Apply monitor settings from the Settings app, with a safe way back.

  display.py apply '<json>'   json: [{name, enabled, mode, scale, transform, vrr, place}]
  display.py keep             accept the change
  display.py revert           go back to what was active before the last apply

`place` is "auto", or "right-of:NAME", "left-of:NAME", "above:NAME", "below:NAME",
"mirror:NAME". apply writes quickshell/state/display.lua (loaded by monitors.lua at login),
applies it live, and starts a watchdog that reverts after 17 s unless `keep` ran, so a
bad mode can never strand you on a black screen.
"""
import json, os, subprocess, sys

HOME = os.path.expanduser("~")
STATE = f"{HOME}/.config/quickshell/state"
LUA = f"{STATE}/display.lua"
PREV = f"{STATE}/display.prev.json"
SELF = os.path.abspath(__file__)


def hypr_monitors():
    out = subprocess.run(["hyprctl", "monitors", "all", "-j"], capture_output=True, text=True).stdout
    return json.loads(out or "[]")


def snapshot():
    cfg = []
    for m in hypr_monitors():
        cfg.append({"name": m["name"], "enabled": not m.get("disabled", False),
                    "mode": f'{m["width"]}x{m["height"]}@{m["refreshRate"]:.2f}',
                    "scale": round(m["scale"], 4), "transform": m["transform"],
                    "vrr": 1 if m.get("vrr") else 0, "place": f'at:{m["x"]}x{m["y"]}'})
    return cfg


def logical(c):
    w, h = (int(v) for v in c["mode"].split("@")[0].split("x"))
    if c.get("transform", 0) in (1, 3, 5, 7):
        w, h = h, w
    return round(w / c["scale"]), round(h / c["scale"])


def positions(cfg):
    """Resolve each monitor's `place` to an explicit XxY string (or "auto")."""
    pos, mirror = {}, {}
    by = {c["name"]: c for c in cfg}
    todo = [c for c in cfg if c.get("enabled", True)]
    if any(":" in c.get("place", "") and not c["place"].startswith("at:") for c in todo):
        anchor = next((c for c in todo if c.get("place", "auto") == "auto"), None)
        if anchor:
            pos[anchor["name"]] = (0, 0)
    for _ in range(len(todo) + 1):
        for c in todo:
            n, place = c["name"], c.get("place", "auto")
            if n in pos or n in mirror:
                continue
            if place.startswith("at:"):
                pos[n] = tuple(int(v) for v in place[3:].split("x"))
            elif place == "auto":
                pos[n] = "auto"
            else:
                rel, target = place.split(":", 1)
                if rel == "mirror":
                    mirror[n] = target
                elif target in pos and pos[target] != "auto":
                    tx, ty = pos[target]
                    tw, th = logical(by[target])
                    w, h = logical(c)
                    pos[n] = {"right-of": (tx + tw, ty), "left-of": (tx - w, ty),
                              "above": (tx, ty - h), "below": (tx, ty + th)}[rel]
                elif target in by and by[target].get("place", "auto") == "auto" and target not in pos:
                    pass  # resolved on a later pass
    for c in todo:
        pos.setdefault(c["name"], "auto")
    return pos, mirror


def lua(cfg):
    pos, mirror = positions(cfg)
    lines = []
    for c in cfg:
        n = c["name"]
        if not c.get("enabled", True):
            lines.append(f'hl.monitor({{ output = "{n}", disabled = true }})')
            continue
        p = pos.get(n, "auto")
        p = p if p == "auto" else f"{p[0]}x{p[1]}"
        parts = [f'output = "{n}"', f'mode = "{c["mode"]}"', f'position = "{p}"', f'scale = {c["scale"]}']
        if c.get("transform"):
            parts.append(f'transform = {int(c["transform"])}')
        if c.get("vrr"):
            parts.append(f'vrr = {int(c["vrr"])}')
        if n in mirror:
            parts.append(f'mirror = "{mirror[n]}"')
        lines.append("hl.monitor({ " + ", ".join(parts) + " })")
    return lines


def push(cfg):
    lines = lua(cfg)
    os.makedirs(STATE, exist_ok=True)
    with open(LUA, "w") as f:
        f.write("-- Generated by scripts/display.py from Settings > Display. Do not edit.\n" + "\n".join(lines) + "\n")
    for line in lines:
        subprocess.run(["hyprctl", "eval", line], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "apply":
        cfg = json.loads(sys.argv[2])
        if not os.path.exists(PREV):
            with open(PREV, "w") as f:
                json.dump(snapshot(), f)
        push(cfg)
        subprocess.Popen(["setsid", "sh", "-c", f'sleep 17; [ -e "{PREV}" ] && "{SELF}" revert'],
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    elif cmd == "keep":
        try:
            os.remove(PREV)
        except OSError:
            pass
    elif cmd == "revert":
        try:
            with open(PREV) as f:
                prev = json.load(f)
        except (OSError, ValueError):
            return
        push(prev)
        os.remove(PREV)
    else:
        sys.exit(__doc__)


main()
