#!/usr/bin/env bash
# Build the key bindings Hyprland loads.
#   apply-keybinds.sh            merge defaults + your changes, write binds.lua, reload Hyprland
#   apply-keybinds.sh --defaults write binds-default.lua from the defaults only (no reload)
# Defaults live in hypr/keybind-defaults.json. Your changes are saved by Settings > Keybinds
# in quickshell/state/keybinds.json: {"overrides": {"<id>": {"mods": [], "key": "", "enabled": true}},
# "custom": [{"id": "custom-1", "label": "...", "mods": [], "key": "", "command": "...", "enabled": true}]}
exec python3 - "$@" <<'PY'
import json, os, subprocess, sys
home = os.path.expanduser("~")
hypr = home + "/.config/hypr"
defaults = json.load(open(hypr + "/keybind-defaults.json"))
user_path = home + "/.config/quickshell/state/keybinds.json"
only_defaults = "--defaults" in sys.argv
user = {}
if not only_defaults and os.path.exists(user_path):
    try:
        user = json.load(open(user_path))
    except Exception:
        user = {}
ov = user.get("overrides", {})
rows = []
for d in defaults:
    o = ov.get(d["id"], {})
    rows.append({"id": d["id"], "mods": o.get("mods", d["mods"]), "key": o.get("key", d["key"]),
                 "enabled": o.get("enabled", True), "modsOnly": d.get("modsOnly", False)})
for c in user.get("custom", []):
    rows.append({"id": c["id"], "mods": c.get("mods", []), "key": c.get("key", ""),
                 "enabled": c.get("enabled", True), "command": c.get("command", "")})

def q(s): return json.dumps(s)
lines = ["-- Generated by apply-keybinds.sh from keybind-defaults.json" + ("" if only_defaults else " and Settings > Keybinds") + ". Do not edit.", "return {"]
for r in rows:
    f = "{ id = %s, mods = {%s}, key = %s, enabled = %s" % (q(r["id"]), ", ".join(q(m) for m in r["mods"]), q(r["key"]), "true" if r["enabled"] else "false")
    if r.get("modsOnly"): f += ", modsOnly = true"
    if "command" in r: f += ", command = " + q(r["command"])
    lines.append("    " + f + " },")
lines.append("}")
out = hypr + ("/binds-default.lua" if only_defaults else "/binds.lua")
open(out, "w").write("\n".join(lines) + "\n")
if not only_defaults:
    subprocess.run(["hyprctl", "reload"], stdout=subprocess.DEVNULL)
PY
