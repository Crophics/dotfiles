#!/usr/bin/env bash
# Apply the idle/lid settings saved by Settings > Session.
# Reads ~/.config/quickshell/state/session.json ({lockMin, suspendMin, graceSec}; 0 = off),
# writes ~/.config/hypr/hypridle-user.conf and restarts hypridle with it.
# The lid grace time is read by sleep-hook.sh straight from the same file.
set -euo pipefail
state="$HOME/.config/quickshell/state/session.json"
out="$HOME/.config/hypr/hypridle-user.conf"
[ -r "$state" ] || exit 0

lock=$(jq -r '.lockMin // 5' "$state")
suspend=$(jq -r '.suspendMin // 15' "$state")
dim=$(jq -r '.dim // true' "$state")

# Dim 30 s before the first timer fires.
first=0
for m in "$lock" "$suspend"; do
    [ "$m" -gt 0 ] && { [ "$first" -eq 0 ] || [ "$((m * 60))" -lt "$first" ] ; } && first=$((m * 60))
done

{
    cat <<'CONF'
# Generated by apply-session-prefs.sh from Settings > Session. Do not edit.
general {
    lock_cmd = ~/.config/qylock/lock.sh
    before_sleep_cmd = ~/.config/hypr/scripts/sleep-hook.sh before
    after_sleep_cmd = ~/.config/hypr/scripts/sleep-hook.sh after
}
CONF
    if [ "$dim" = true ] && [ "$first" -gt 30 ]; then
        printf '\nlistener {\n    timeout = %s\n    on-timeout = brightnessctl -s set 10%%\n    on-resume = brightnessctl -r\n}\n' "$((first - 30))"
    fi
    if [ "$lock" -gt 0 ]; then
        printf '\nlistener {\n    timeout = %s\n    on-timeout = loginctl lock-session\n}\n' "$((lock * 60))"
    fi
    if [ "$suspend" -gt 0 ]; then
        printf '\nlistener {\n    timeout = %s\n    on-timeout = ~/.config/hypr/scripts/suspend.sh\n}\n' "$((suspend * 60))"
    fi
} > "$out"

"$HOME/.config/hypr/scripts/start-hypridle.sh" restart
