#!/usr/bin/env bash
# Apply the window settings saved by Settings > Windows.
# Reads ~/.config/quickshell/state/windows.json, writes ~/.config/hypr/prefs.lua (loaded by
# look.lua and rules.lua), and applies the change to the running Hyprland.
#   apply-window-prefs.sh          border, rounding and gaps change live
#   apply-window-prefs.sh opacity  also updates window opacity (needs a config reload)
set -euo pipefail
state="$HOME/.config/quickshell/state/windows.json"
out="$HOME/.config/hypr/prefs.lua"
[ -r "$state" ] || exit 0

get() { jq -r --arg k "$1" --arg d "$2" '.[$k] // $d' "$state"; }
opacity=$(get opacity 0.9); border=$(get borderSize 2); round=$(get rounding 8); gaps=$(get gapsIn 4)

old=$(sed -nE 's/.*opacity = ([0-9.]+).*/\1/p' "$out" 2>/dev/null || true)

cat > "$out" <<LUA
-- Generated by apply-window-prefs.sh from Settings > Windows. Do not edit.
return { opacity = $opacity, border_size = $border, rounding = $round, gaps_in = $gaps }
LUA

if [ "${1:-}" = "opacity" ]; then
    if [ "$old" != "$opacity" ]; then
        # Rofi follows the window opacity (hex alpha byte), but only when it really changed.
        alpha=$(printf '%02X' "$(awk -v o="$opacity" 'BEGIN { printf "%d", o * 255 + 0.5 }')")
        sed -i -E "s/(bg:[[:space:]]*#[0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?;/\1$alpha;/" "$HOME/.config/rofi/colors.rasi" 2>/dev/null || true
    fi
    # Shell panels use the same value; Theme.qml keeps it across restarts.
    sed -i -E "s/(property real bgAlpha: )[0-9.]+/\1$opacity/" "$HOME/.config/quickshell/Theme.qml"
    hyprctl reload >/dev/null
else
    hyprctl eval "hl.config({ general = { border_size = $border, gaps_in = $gaps }, decoration = { rounding = $round } })" >/dev/null
fi
