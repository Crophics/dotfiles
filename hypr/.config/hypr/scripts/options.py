#!/usr/bin/env python3
"""Settings engine: one registry (hypr/options.json) describes every option the Settings app
shows; the user's changes live in quickshell/state/options.json.

  options.py set <id> <json>   save one value and apply it
  options.py reset <id>...     back to the default and apply
  options.py reset-all         every option back to its default
  options.py apply <id>...     re-apply (after the state file was written elsewhere)
  options.py build             regenerate hypr/options.lua and hypr/prefs.lua only

Options with a "path" become hl.config entries in hypr/options.lua (loaded last, so they win).
Options with a "pref" go to hypr/prefs.lua, which look.lua and rules.lua read. "apply" is
"live" (hyprctl eval) or "reload". A "hook" runs extra work after a change.
"""
import json, os, re, subprocess, sys

HOME = os.path.expanduser("~")
REGISTRY = f"{HOME}/.config/hypr/options.json"
STATE = f"{HOME}/.config/quickshell/state/options.json"
OLD_STATE = f"{HOME}/.config/quickshell/state/windows.json"
OPTIONS_LUA = f"{HOME}/.config/hypr/options.lua"
PREFS_LUA = f"{HOME}/.config/hypr/prefs.lua"


def load(path, default):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def registry():
    return {o["id"]: o for o in load(REGISTRY, {"options": []})["options"] if "path" in o or "pref" in o}


def state(reg):
    s = load(STATE, None)
    if s is None:  # first run: carry over the old Windows settings
        old = load(OLD_STATE, {})
        speed = {"fast": 0.7, "normal": 1.0, "relaxed": 1.5}.get(old.get("animSpeed", "normal"), 1.0)
        s = {k: v for k, v in {
            "windows.opacity": old.get("opacity"),
            "general.border_size": old.get("borderSize"),
            "decoration.rounding": old.get("rounding"),
            "general.gaps_in": old.get("gapsIn"),
            "windows.animations": old.get("animations"),
            "windows.anim_speed": speed if "animSpeed" in old else None,
        }.items() if v is not None}
        s = {k: v for k, v in s.items() if k in reg and v != reg[k].get("default")}
        save(s)
    return s


def save(s):
    os.makedirs(os.path.dirname(STATE), exist_ok=True)
    tmp = STATE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(s, f, indent=1)
    os.replace(tmp, STATE)


def lua(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_table(d):
    return "{ " + ", ".join(f"{k} = " + (lua_table(v) if isinstance(v, dict) else lua(v)) for k, v in d.items()) + " }"


def nest(pairs):
    root = {}
    for path, v in pairs:
        node = root
        parts = path.split(".")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = v
    return root


def value(reg, s, i):
    return s.get(i, reg[i].get("default"))


def build(reg, s):
    cfg = [(o["path"], s[i]) for i, o in reg.items() if "path" in o and i in s]
    with open(OPTIONS_LUA, "w") as f:
        f.write("-- Generated by scripts/options.py from Settings. Do not edit.\n")
        if cfg:
            f.write(f"hl.config({lua_table(nest(cfg))})\n")
    prefs = {o["pref"]: s[i] for i, o in reg.items() if "pref" in o and i in s}
    with open(PREFS_LUA, "w") as f:
        f.write("-- Generated by scripts/options.py from Settings. Do not edit.\n")
        f.write(f"return {lua_table(prefs)}\n")


def hook_opacity(v):
    alpha = "%02X" % int(v * 255 + 0.5)
    rasi = f"{HOME}/.config/rofi/colors.rasi"
    theme = f"{HOME}/.config/quickshell/Theme.qml"
    for path, pat, rep in ((rasi, r"(bg:\s*#[0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?;", r"\g<1>" + alpha + ";"),
                           (theme, r"(property real bgAlpha: )[0-9.]+", r"\g<1>" + str(v))):
        try:
            text = open(path).read()
            new = re.sub(pat, rep, text)
            if new != text:
                open(path, "w").write(new)
        except OSError:
            pass


def hyprctl(*args):
    subprocess.run(["hyprctl", *args], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def apply(reg, s, ids):
    build(reg, s)
    live, reload = [], False
    for i in dict.fromkeys(ids):
        o = reg.get(i)
        if not o:
            continue
        if o.get("hook") == "opacity":
            hook_opacity(value(reg, s, i))
        if o.get("apply", "live" if "path" in o else "reload") == "reload":
            reload = True
        elif "path" in o:
            live.append((o["path"], value(reg, s, i)))
    if reload:
        hyprctl("reload")
    elif live:
        hyprctl("eval", f"hl.config({lua_table(nest(live))})")


def main():
    cmd, args = (sys.argv[1] if len(sys.argv) > 1 else ""), sys.argv[2:]
    reg = registry()
    s = state(reg)
    if cmd == "set" and len(args) == 2 and args[0] in reg:
        v = json.loads(args[1])
        if v == reg[args[0]].get("default"):
            s.pop(args[0], None)
        else:
            s[args[0]] = v
        save(s)
        apply(reg, s, [args[0]])
    elif cmd == "reset":
        for i in args:
            s.pop(i, None)
        save(s)
        apply(reg, s, args)
    elif cmd == "reset-all":
        save({})
        apply(reg, {}, list(reg))
    elif cmd == "apply":
        apply(reg, s, args)
    elif cmd == "build":
        build(reg, s)
    else:
        sys.exit(__doc__)


main()
